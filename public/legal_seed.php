function upsertInfo(PDO $pdo, string $p, int $id, int $lang, string $title, string $desc, string $mt, string $md, string $mk): void {
    $pdo->exec("INSERT INTO `{$p}information` (information_id, bottom, sort_order, status)
        VALUES ($id, 0, $id, 1)
        ON DUPLICATE KEY UPDATE status=1");
    $pdo->exec("INSERT INTO `{$p}information_to_store` (information_id, store_id)
        VALUES ($id, 0)
        ON DUPLICATE KEY UPDATE store_id=0");
    $st = $pdo->prepare("INSERT INTO `{$p}information_description`
        (information_id, language_id, title, description, meta_title, meta_description, meta_keyword, meta_h1)
        VALUES (:id, :lang, :title, :desc, :mt, :md, :mk, '')
        ON DUPLICATE KEY UPDATE
            title=VALUES(title), description=VALUES(description),
            meta_title=VALUES(meta_title), meta_description=VALUES(meta_description),
            meta_keyword=VALUES(meta_keyword)");
    $st->execute([':id'=>$id,':lang'=>$lang,':title'=>$title,':desc'=>$desc,':mt'=>$mt,':md'=>$md,':mk'=>$mk]);
}

function upsertSeo(PDO $pdo, string $p, string $query, string $keyword): void {
    $pdo->prepare("INSERT INTO `{$p}seo_url` (store_id, language_id, query, keyword)
        VALUES (0, 1, :q, :k)
        ON DUPLICATE KEY UPDATE keyword=VALUES(keyword)")
        ->execute([':q'=>$query, ':k'=>$keyword]);
}

